"""Quality rules: what counts as a bot, a speeder, a bad answer, or fraud for one project.

Every project starts on the defaults. Researchers can change them before the survey
goes live. Dashboard rules apply whenever results load, so edits take effect at once;
in-survey rules (termination, privacy notice) are written into the survey when it
is next programmed in Decipher.
"""

from typing import Any

from pydantic import BaseModel, Field, field_validator
from sqlalchemy.orm import Session
from sqlalchemy.orm.attributes import flag_modified

from app.repositories.records import ProjectRepository

# Decisive bot signals reported by the bot-detection service, with plain labels.
BOT_SIGNALS: dict[str, str] = {
    "automation": "Automated or headless browser",
    "scripted_input": "Clicks and key presses generated by script",
    "no_input": "Pages answered with no mouse or keyboard use",
    "honeypot": "Hidden honeypot field filled in",
    "untyped_answers": "Open ends that appeared without typing",
}

# Reasons the text check can give for a poor open-ended answer.
TEXT_REASONS: dict[str, str] = {
    "gibberish": "Gibberish",
    "generic": 'Generic ("good", "nothing")',
    "irrelevant": "Off-topic",
    "copy_paste": "Copied or repeated text",
    "low_quality": "Low effort",
}

DEFAULT_PRIVACY_TEXT = (
    "To keep results genuine, this survey checks how answers are entered "
    "(for example typing, pasting, and time spent). It does not read anything outside this survey."
)


class QualityRules(BaseModel):
    """One project's quality rules. Field defaults are the recommended settings."""

    # Bot detection
    bot_threshold: float = Field(0.7, ge=0.3, le=0.99)
    bot_signals: list[str] = Field(default_factory=lambda: list(BOT_SIGNALS))

    # Speed and attention
    speeder_page_seconds: float = Field(3.5, ge=0.5, le=60)
    speeder_median_share: float = Field(0.5, ge=0, le=0.9)
    straightline_min_rows: int = Field(3, ge=2, le=30)

    # Open ends
    text_reasons: list[str] = Field(default_factory=lambda: list(TEXT_REASONS))
    flag_pasted: bool = True

    # Fraud
    fraud_threshold: float = Field(0.7, ge=0.3, le=0.99)
    flag_duplicates: bool = True
    flag_datacenter: bool = True

    # During the survey (written into the Decipher survey when it is programmed)
    terminate_in_survey: bool = True
    terminate_after_page: int = Field(2, ge=1, le=10)
    terminate_signals: list[str] = Field(default_factory=lambda: list(BOT_SIGNALS))
    privacy_notice: bool = True
    privacy_text: str = Field(DEFAULT_PRIVACY_TEXT, min_length=10, max_length=400)

    @field_validator("bot_signals", "terminate_signals")
    @classmethod
    def _known_signals(cls, value: list[str]) -> list[str]:
        unknown = sorted(set(value) - set(BOT_SIGNALS))
        if unknown:
            raise ValueError(f"Unknown bot signals: {', '.join(unknown)}")
        return [code for code in BOT_SIGNALS if code in value]

    @field_validator("text_reasons")
    @classmethod
    def _known_reasons(cls, value: list[str]) -> list[str]:
        unknown = sorted(set(value) - set(TEXT_REASONS))
        if unknown:
            raise ValueError(f"Unknown text reasons: {', '.join(unknown)}")
        return [code for code in TEXT_REASONS if code in value]

    @field_validator("privacy_text")
    @classmethod
    def _safe_text(cls, value: str) -> str:
        text = " ".join(value.split())
        if "$" in text or "`" in text or "]]>" in text or text.startswith("@"):
            raise ValueError("The privacy notice cannot contain $, backticks, or ]]>.")
        return text


# Rules that only change when the survey is programmed again.
SURVEY_FIELDS = (
    "terminate_in_survey",
    "terminate_after_page",
    "terminate_signals",
    "privacy_notice",
    "privacy_text",
)


def defaults() -> QualityRules:
    """Return the recommended rules."""
    return QualityRules()


def get_rules(db: Session, project_id: str) -> QualityRules:
    """Return a project's rules (defaults for anything it has not changed).

    Args:
        db: Session.
        project_id: Project id.

    Returns:
        The project's rules.
    """
    project = ProjectRepository(db).get(project_id)
    stored = ((project.study_context or {}).get("live_quality") or {}).get("rules") or {}
    try:
        return QualityRules(**stored)
    except ValueError:
        return QualityRules()


def save_rules(db: Session, project_id: str, rules: QualityRules | None) -> QualityRules:
    """Store a project's rules; ``None`` restores the defaults.

    Args:
        db: Session.
        project_id: Project id.
        rules: New rules, or None.

    Returns:
        The rules now in force.
    """
    project = ProjectRepository(db).get(project_id)
    context = dict(project.study_context or {})
    current = dict(context.get("live_quality") or {})
    if rules is None:
        current.pop("rules", None)
    else:
        current["rules"] = rules.model_dump()
    context["live_quality"] = current
    project.study_context = context
    flag_modified(project, "study_context")
    db.flush()
    return get_rules(db, project_id)


def changed_fields(rules: QualityRules) -> list[str]:
    """Names of the rules that differ from the defaults."""
    base = defaults().model_dump()
    return [name for name, value in rules.model_dump().items() if base[name] != value]


def describe() -> dict[str, Any]:
    """Labels the rules editor shows for signals and text reasons."""
    return {
        "bot_signals": BOT_SIGNALS,
        "text_reasons": TEXT_REASONS,
        "survey_fields": list(SURVEY_FIELDS),
    }


def survey_rules(rules: QualityRules) -> dict[str, Any]:
    """The in-survey part of the rules, as written into the Decipher survey.

    Args:
        rules: Project rules.

    Returns:
        ``terminate``, ``after_page``, ``signals``, and ``privacy_text`` (empty when off).
    """
    return {
        "terminate": rules.terminate_in_survey and bool(rules.terminate_signals),
        "after_page": rules.terminate_after_page,
        "signals": list(rules.terminate_signals),
        "privacy_text": rules.privacy_text if rules.privacy_notice else "",
    }
